export const SPEC_UNITS = ["piece", "gram", "kilogram", "liter", "milliliter", "meter", "centimeter", "box", "set", "other"];

const SPEC_UNIT_KEYS = {
  piece: "unitPiece",
  gram: "unitGram",
  kilogram: "unitKilogram",
  liter: "unitLiter",
  milliliter: "unitMilliliter",
  meter: "unitMeter",
  centimeter: "unitCentimeter",
  box: "unitBox",
  set: "unitSet",
  other: "unitOther",
};

export function specUnitLabel(unit, t) {
  if (!unit) return "";
  const key = SPEC_UNIT_KEYS[unit];
  return key ? t(key) : unit;
}

export function specLabel(p, t) {
  const qty = p?.spec_quantity;
  const unit = specUnitLabel(p?.spec_unit, t);
  if (qty == null && !unit) return null;
  return [qty != null ? String(qty) : "", unit].filter(Boolean).join(" ");
}
